/**
 * Generates src/styles/dark-compat.css in both apps from Tailwind's own palette.
 * Run from the repo root (needs frontend/node_modules): node scripts/generate-dark-compat.mjs
 */
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const theme = fs.readFileSync(path.join(root, 'frontend/node_modules/tailwindcss/theme.css'), 'utf8')

const HUES = [
  'red', 'orange', 'amber', 'yellow', 'lime', 'green', 'emerald', 'teal', 'cyan',
  'sky', 'blue', 'indigo', 'violet', 'purple', 'fuchsia', 'pink', 'rose',
]

const palette = (hue, shade) => {
  const match = theme.match(new RegExp(`--color-${hue}-${shade}:\\s*([^;]+);`))
  if (!match) throw new Error(`Missing --color-${hue}-${shade} in Tailwind theme`)
  return match[1].trim()
}

/* Light tints go dark and dark text goes light. 300-500 stay, so white-on-fill still reads. */
const hueLines = HUES.flatMap((hue) => {
  const mid = palette(hue, 500)
  const tint = (pct) => `color-mix(in oklab, ${mid} ${pct}%, #111e1b)`
  return [
    `  --color-${hue}-50: ${tint(14)};`,
    `  --color-${hue}-100: ${tint(22)};`,
    `  --color-${hue}-200: ${tint(34)};`,
    `  --color-${hue}-700: ${palette(hue, 300)};`,
    `  --color-${hue}-800: ${palette(hue, 200)};`,
    `  --color-${hue}-900: ${palette(hue, 100)};`,
    `  --color-${hue}-950: ${palette(hue, 50)};`,
  ]
})

/* 600 stays a fill for white text, so as a text colour it has to be lifted separately */
const text600Lines = HUES.flatMap((hue) => [
  `[data-theme='dark'] .text-${hue}-600 {`,
  `  color: ${palette(hue, 400)};`,
  '}',
])

const NEUTRALS = ['gray', 'slate']
const DARK_NEUTRALS = {
  50: '#0d1917', 100: '#172723', 200: '#24352f', 300: '#395048', 400: '#7f918c',
  500: '#93a6a0', 600: '#a8b8b3', 700: '#c0cdc9', 800: '#d8e2df', 900: '#eaf3f0', 950: '#f4f9f7',
}
const LIGHT_NEUTRALS = {
  50: '#f5f7f5', 100: '#edf1ee', 200: '#dde4df', 300: '#c5cfc9', 400: '#94a39d',
  500: '#5f706a', 600: '#4a5a55', 700: '#3a4945', 800: '#27352f', 900: '#162420', 950: '#0b1613',
}
const neutralLines = (values) =>
  NEUTRALS.flatMap((name) =>
    Object.entries(values).map(([shade, value]) => `  --color-${name}-${shade}: ${value};`),
  )

const css = `/*
 * GENERATED by scripts/generate-dark-compat.mjs. Do not edit by hand.
 *
 * Gives pages written with raw Tailwind colours (bg-white, text-gray-700, bg-blue-50...)
 * a working dark theme without editing them, by remapping the palette variables those
 * utilities read. New code should use the semantic tokens in tokens.css instead.
 */

:root[data-theme='dark'] {
  --color-white: var(--color-surface);
${neutralLines(DARK_NEUTRALS).join('\n')}
${hueLines.join('\n')}
}

/* Literal white stays white where it is text, and in anything nested in that text's fill */
[data-theme='dark'] [class*='text-white'] {
  --color-white: #fff;
}

/* ...but a solid bg-white is always a surface */
[data-theme='dark'] [class*='bg-white']:not([class*='bg-white/']) {
  --color-white: var(--color-surface);
}

/* Fills that are dark in both themes keep the light-theme neutrals inside them */
[data-theme='dark'] .bg-gray-800,
[data-theme='dark'] .bg-gray-900,
[data-theme='dark'] .bg-gray-950,
[data-theme='dark'] .bg-slate-700,
[data-theme='dark'] .bg-slate-800,
[data-theme='dark'] .bg-slate-900,
[data-theme='dark'] .bg-slate-950,
[data-theme='dark'] .from-gray-900,
[data-theme='dark'] .from-slate-800,
[data-theme='dark'] .from-slate-900 {
${neutralLines(LIGHT_NEUTRALS).join('\n')}
}

/* Translucent neutral fills are scrims: keep them dark without changing what they hold */
[data-theme='dark'] .bg-gray-950\\/50,
[data-theme='dark'] .bg-slate-900\\/50,
[data-theme='dark'] .bg-slate-900\\/60 {
  background-color: var(--color-scrim);
}

[data-theme='dark'] .text-black {
  color: var(--color-ink);
}

/* The brand fill is too dark to read as text on dark surfaces */
[data-theme='dark'] .text-primary {
  color: var(--color-brand);
}

${text600Lines.join('\n')}

/* Hard-coded hex values left in older pages */
.bg-\\[\\#F8F9FD\\],
.bg-\\[\\#f4f6fb\\] {
  background-color: var(--color-canvas);
}

.bg-\\[\\#F2F3FF\\] {
  background-color: var(--color-primary-soft);
}

.text-\\[\\#515151\\],
.text-\\[\\#5E5E5E\\] {
  color: var(--color-ink-2);
}

.border-\\[\\#DADADA\\] {
  border-color: var(--color-line);
}
`

for (const app of ['frontend', 'admin']) {
  const dir = path.join(root, app, 'src/styles')
  fs.mkdirSync(dir, { recursive: true })
  fs.writeFileSync(path.join(dir, 'dark-compat.css'), css)
}
